/// The riddle banks: two hundred and fifty in each language, drawn in a shuffled order by
/// `providers/riddle_provider.dart` whenever a player spends their last life
/// and wants to carry on.
///
/// Rules of the bank, pinned by `test/data/riddle_bank_test.dart`:
/// * ids run 1..[kRiddleCount] in every language, so the deck can shuffle
///   ids and mean the same thing whichever language is on;
/// * the answer is one everyday word — this is a five-second gate, not a
///   crossword — and near misses (a plural, a tense, a typo) are the
///   matcher's job, not the bank's, so [Riddle.alternates] lists only words
///   the matcher could not reach on its own: real synonyms, and — for the
///   Hindi bank — the romanized spellings ('paani', 'jal'), because plenty of
///   phones that are set to Hindi have no Devanagari keyboard on them, and a
///   gate you cannot type into is not a gate;
/// * every riddle carries a hint that narrows it down without saying it.
///
/// A riddle is *not* a translation of the riddle with the same id in the
/// other bank: a pun that works in English rarely survives the crossing, so
/// the Hindi bank is its own set of पहेलियाँ.
library;

import '../models/riddle.dart';

/// How many riddles each bank holds.
const int kRiddleCount = 250;

/// The bank for [languageCode] ('hi' for Hindi, English otherwise).
List<Riddle> riddleBankFor(String languageCode) =>
    languageCode == 'hi' ? hindiRiddles : englishRiddles;

/// The riddle with [id] in [languageCode]'s bank, or the first one when the
/// id is not in the bank (a deck written by a future, longer bank).
Riddle riddleFor(String languageCode, int id) {
  final bank = riddleBankFor(languageCode);
  return bank.firstWhere((r) => r.id == id, orElse: () => bank.first);
}

